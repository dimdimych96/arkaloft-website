export default async function handler(req: VercelRequest, res: VercelResponse) {
  // CORS headers для локального тестирования
  res.setHeader('Access-Control-Allow-Credentials', 'true');
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'GET,OPTIONS,PATCH,DELETE,POST,PUT');
  res.setHeader(
    'Access-Control-Allow-Headers',
    'X-CSRF-Token, X-Requested-With, Accept, Accept-Version, Content-Length, Content-MD5, Content-Type, Date, X-Api-Version'
  );

  if (req.method === 'OPTIONS') {
    return res.status(200).end();
  }

  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const { messages } = req.body;

  if (!messages || !Array.isArray(messages)) {
    return res.status(400).json({ error: 'Параметр messages должен быть массивом' });
  }

  const apiKey = process.env.OPENROUTER_API_KEY;
  if (!apiKey) {
    return res.status(500).json({ error: 'OPENROUTER_API_KEY не задан в переменных окружения бэкенда' });
  }

  try {
    // Форматируем историю сообщений под требования OpenAI/OpenRouter API
    const currentDateTime = new Date().toLocaleString('ru-RU', { timeZone: 'Asia/Novosibirsk' });
    const dynamicSystemPrompt = `${SYSTEM_PROMPT}\n\nСИСТЕМНАЯ ИНФОРМАЦИЯ:\nТекущая дата и время: ${currentDateTime} (Новосибирск). Обязательно учитывай это, если клиент говорит "сегодня", "завтра" или называет день недели!`;

    const formattedMessages = [
      { role: 'system', content: dynamicSystemPrompt },
      ...messages.map((msg: any) => ({
        role: msg.role === 'assistant' || msg.role === 'model' ? 'assistant' : 'user',
        content: msg.text || msg.content || ''
      }))
    ];

    const openRouterUrl = 'https://openrouter.ai/api/v1/chat/completions';

    const payload = {
      model: 'openrouter/free',
      models: [
        'openrouter/free',
        'minimax/minimax-m3:free',
        'z-ai/glm-5.2:free',
        'minimax/minimax-m2.7:free',
        'nvidia/nemotron-3.5-lightning:free',
        'google/gemma-4-31b-it:free'
      ],
      messages: formattedMessages,
      temperature: 0.7,
      max_tokens: 1000,
      top_p: 0.95
    };

    const response = await axios.post(openRouterUrl, payload, {
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${apiKey}`,
        'HTTP-Referer': 'https://arkaloft.ru',
        'X-Title': 'Arkaloft'
      },
      timeout: 25000 // 25 секунд лимит ожидания
    });

    const candidate = response.data?.choices?.[0];
    const replyText = candidate?.message?.content || 'Извините, не удалось получить ответ. Попробуйте еще раз!';

    return res.status(200).json({
      reply: replyText
    });
  } catch (error: any) {
    const errorDetails = error.response?.data || error.message;
    console.error('OpenRouter API error full:', JSON.stringify(errorDetails));
    return res.status(500).json({
      error: 'Ошибка при обращении к ИИ',
      details: error.response?.data?.error?.message || error.message
    });
  }
}
